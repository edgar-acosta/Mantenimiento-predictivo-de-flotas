def _lookup(value: rx.Var | str, dictionary: dict[str, str]) -> rx.Var | str:
    if isinstance(value, str):
        return dictionary.get(value, value)
    return rx.Var.create(dictionary).get(value, value)


def translate(value: rx.Var | str) -> rx.Var:
    from app.states.access_state import AccessState

    return rx.cond(
        AccessState.language == "en",
        _lookup(value, {**TRANSLATIONS, **STATUS_EN}),
        _lookup(value, STATUS_ES),
    )


